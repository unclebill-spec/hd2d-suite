def paint(rows, name):
    if len(rows) != 32:
        raise SystemExit(f'{name}: expected 32 rows, got {len(rows)}')
    rows = [r.ljust(32, '.') for r in rows]
    if any(len(r) != 32 for r in rows):
        raise SystemExit(f'{name}: a row is longer than 32')
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in PAL:
                raise SystemExit(f'{name}: bad pixel {ch!r} at {x},{y}')
            px[x, y] = PAL[ch]
    im.save(HERE / name)


if __name__ == '__main__':
    paint(ARROW, 'cursor_arrow.png')
    paint(HAND, 'cursor_hand.png')
