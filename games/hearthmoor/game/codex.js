function flagAt(root, path) {
  let cur = root;
  for (const part of path.split('.')) {
    if (cur == null || typeof cur !== 'object') return undefined;
    cur = cur[part];
  }
  return cur;
}

// unlock: always | alliance.<realm> | flags.<a>[.<b>] | met.<id> | merit.<f> | quests.<id>
export function isUnlocked(S, entry) {
  const unlock = entry && entry.unlock;
  if (unlock === 'always') return true;
  if (typeof unlock !== 'string') return false;
  const save = S || {};
  const dot = unlock.indexOf('.');
  if (dot < 1) return false;
  const kind = unlock.slice(0, dot);
  const rest = unlock.slice(dot + 1);
  if (!rest) return false;
  if (kind === 'alliance') {
    const al = save.flags && save.flags.alliance;
    return !!(al && al[rest]);
  }
  if (kind === 'flags') return !!flagAt(save.flags, rest);
  if (kind === 'met') return !!(save.met && save.met[rest]);
  if (kind === 'merit') return ((save.merit || {})[rest] || 0) > 0;
  if (kind === 'quests') return !!(save.quests && save.quests[rest] === 3);
  return false;
}

export function unlockedEntries(S) {
  return CODEX.filter((entry) => isUnlocked(S, entry));
}
